let viewport: Dungeon3DViewport | undefined,
  revision = 0,
  comparisonRevision = 0,
  disposed = false
const focusOptions = computed(() => {
  const options = [{ value: 'map', label: 'Full dungeon' }],
    plan = currentPlan.value
  if (!plan || !floor.value) return options
  const largest = [...floor.value.rooms].sort((a, b) => b.width * b.height - a.width * a.height)[0]
  const known = (x: number, y: number) =>
    !walk.state.active || walk.state.explored.has(y * floor.value!.width + x)
  if (largest && !walk.state.active)
    options.push({ value: `room:${largest.id}`, label: 'Largest chamber' })
  for (const facing of ['north', 'south', 'east', 'west']) {
    const door = plan.doors.find((d) => d.type === 'regular' && d.facing === facing)
    if (door && known(door.position.x, door.position.y))
      options.push({
        value: `door:${door.id}`,
        label: `${facing[0]!.toUpperCase()}${facing.slice(1)} doorway`,
      })
  }
  for (const stair of plan.stairs) {
    if (!known(stair.position.x, stair.position.y)) continue
    options.push({
      value: `stair:${stair.id}`,
      label: `${stair.direction === 'up' ? 'Upward' : 'Downward'} staircase`,
    })
  }
  return options
})
async function paintComparison() {
  const id = ++comparisonRevision,
    source = floor.value
  if (!source || !compare.value || walk.state.active) return
  const image = await createMapCanvasAsync(source, false, 'ancient', {
    revealSecrets: revealSecrets.value,
    ancient: { doorsOpen: doorsOpen.value, lighting: torchLighting.value },
  })
  try {
    await nextTick()
    if (disposed || id !== comparisonRevision || !comparison.value) return
    comparison.value.width = image.width
    comparison.value.height = image.height
    comparison.value.getContext('2d')!.drawImage(image, 0, 0)
  } finally {
    disposeMapCanvas(image)
  }
}
async function load(reuse = false) {
  const id = ++revision
  busy.value = true
  error.value = ''
  metrics.value = undefined
  viewport?.dispose()
  viewport = undefined
  currentPlan.value = undefined
  try {
    const source =
      reuse && floor.value
        ? floor.value
        : sceneKind.value === 'diagnostic'
          ? createFinishingScene().floor
          : generatePrototypeFloor(seed.value, size.value)
    floor.value = source
    await nextTick()
    if (!host.value || disposed || id !== revision) return
    const next = await createDungeon3DViewport(
      host.value,
      source,
      revealSecrets.value,
      (value) => {
        if (!disposed && id === revision) {
          metrics.value = value
          zoom.value = value.zoom
          elevation.value = value.elevation
          rotation.value = value.rotation
          if (!busy.value && walk.state.active && value.elevation !== 90) exitWalk(false)
        }
      },
      (stairId) => {
        focus.value = stairId ? `stair:${stairId}` : 'map'
      },
    )
    if (disposed || id !== revision) {
      next.dispose()
      return
    }
    viewport = next
    currentPlan.value = next.plan
    next.setCamera(elevation.value, rotation.value)
    if (height.value !== 1) next.setHeight(height.value)
    if (doorsOpen.value) next.setDoorsOpen(true)
    if (doorHeadCutaway.value) next.setDoorHeadCutaway(true)
    next.setTorchLighting(torchLighting.value)
    next.setFlameAnimation(flameAnimation.value)
    next.setShadows(shadows.value)
    next.setContactOcclusion(contactOcclusion.value)
    next.setWireframe(wireframe.value)
    next.setTheme(theme.value)
    next.setEffects(effects.value)
    next.setWalk(walk.state)
    focus.value = 'map'
    await paintComparison()
  } catch (cause) {
    if (id === revision) error.value = cause instanceof Error ? cause.message : String(cause)
  } finally {
    if (id === revision && !disposed) busy.value = false
  }
}
function updateCamera() {
  if (walk.state.active && elevation.value !== 90) exitWalk(false)
  viewport?.setCamera(elevation.value, rotation.value)
}
function updateZoom(value: number | null) {
  if (value !== null) viewport?.setZoom(value)
}
function fit() {
  viewport?.fit()
  zoom.value = 1
  focus.value = 'map'
  viewport?.selectStair(null)
}
function resetCamera() {
  exitWalk(false)
  elevation.value = DEFAULT_CAMERA.elevation
  rotation.value = 0
  zoom.value = 1
  viewport?.reset()
  focus.value = 'map'
  viewport?.selectStair(null)
}
function focusFeature() {
  const [kind, id] = focus.value.split(':')
  if (!viewport) return
  viewport.selectStair(kind === 'stair' ? (id ?? null) : null)
  if (kind === 'map') {
    viewport.fit()
    return
  }
  if (kind === 'door') {
    const door = viewport.plan.doors.find((d) => d.id === id)
    if (door) viewport.focus(door.position.x, door.position.y, 4.8)
  } else if (kind === 'stair') {
    const stair = viewport.assetProof().stairs.find((s) => s.id === id)
    if (stair)
      viewport.focus(
        stair.bounds.x + stair.bounds.width / 2 - 0.5,
        stair.bounds.z + stair.bounds.depth / 2 - 0.5,
        6,
        (stair.floor + stair.destination) / 2,
      )
  } else {
    const room = viewport.plan.floor.rooms.find((r) => r.id === id)
    if (room)
      viewport.focus(
        room.x + room.width / 2 - 0.5,
        room.y + room.height / 2 - 0.5,
        Math.max(room.width, room.height) + 4,
      )
  }
}
function download() {
  if (!viewport) return
  const a = document.createElement('a')
  a.href = viewport.png()
  a.download = `dungeon-3d-${floor.value?.seed ?? 'prototype'}.png`
  a.click()
}
async function copyDebugSettings() {
  if (!viewport || busy.value || copyingSettings.value) return
  copyingSettings.value = true
  copySettingsStatus.value = ''
  try {
    const live = viewport.stats()
    const snapshot = {
      format: 'dungeon-atelier/3d-debug-settings',
      version: 1,
      scene: {
        source: sceneKind.value,
        displayedFloor: {
          seed: floor.value?.seed,
          width: floor.value?.width,
          height: floor.value?.height,
          floorNumber: floor.value?.floorNumber,
          generatorVersion: floor.value?.generatorVersion,
          config: floor.value?.config,
        },
        generationInputs: { seed: seed.value, size: size.value },
        theme: theme.value,
        inspect: focus.value,
        compareWithCanvas: compare.value,
      },
      camera: {
        elevationDegrees: live.elevation,
        rotationDegrees: live.rotation,
        referenceAzimuthDegrees: DEFAULT_CAMERA.referenceAzimuth,
        zoom: viewport.camera.zoom,
        position: viewport.camera.position.toArray(),
        target: viewport.target(),
      },
      architecture: {
        wallHeightMultiplier: height.value,
        doorsOpen: doorsOpen.value,
        doorHeadCutaway: doorHeadCutaway.value,
        revealSecrets: revealSecrets.value,
      },
      rendering: {
        torchLighting: torchLighting.value,
        contactAO: contactOcclusion.value,
        shadows: shadows.value,
        flameFlicker: flameAnimation.value,
        wireframe: wireframe.value,
      },
      walk: {
        active: walk.state.active,
        position: walk.state.position,
        heading: walk.state.heading,
        steps: walk.state.steps,
        exploredTiles: walk.state.explored.size,
      },
      effects: { ...effects.value },
      environment: {
        browser: navigator.userAgent,
        devicePixelRatio: window.devicePixelRatio,
        viewportCssPixels: { width: host.value?.clientWidth, height: host.value?.clientHeight },
        backend: viewport.backend(),
      },
    }
    await copyToClipboard(JSON.stringify(snapshot, null, 2))
    copySettingsStatus.value = 'Settings copied. Ready to paste.'
  } catch {
    copySettingsStatus.value = 'Could not copy settings. Allow clipboard access and try again.'
  } finally {
    copyingSettings.value = false
  }
}
