  measuring = ref(false),
  measurement = shallowRef<Awaited<ReturnType<Dungeon3DViewport['measurePerformance']>>>()
async function measureEffects() {
  if (!viewport || measuring.value) return
  measuring.value = true
  try {
    measurement.value = await viewport.measurePerformance()
  } finally {
    measuring.value = false
  }
}
function applyPreset(preset: EffectPreset) {
  resetEffects()
  effects.value = { ...EFFECT_PRESETS[preset] }
}
function resetEffects() {
  effects.value = { ...BASELINE_EFFECTS }
  shadows.value = true
  torchLighting.value = true
  contactOcclusion.value = true
  wireframe.value = false
}
